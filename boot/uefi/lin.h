/*
 * Fobos OS — ввод с клавиатуры в загрузчике через ConIn (FND-2b).
 *
 * Нужен Setup-мастеру: построчный ввод (эхо/маска), ожидание любой клавиши
 * с таймаутом (окно ESC в boot manager). Работает ДО ExitBootServices —
 * прошивка владеет PS/2-драйвером, мы не трогаем 8042 напрямую.
 */
#ifndef FOBOS_UEFI_LIN_H
#define FOBOS_UEFI_LIN_H

#include <fobos/types.h>

struct EFI_SYSTEM_TABLE;

/* Привязка к таблице (g_st). 0 = успех (ConIn есть). */
int lin_init(struct EFI_SYSTEM_TABLE *st);

/* Неблокирующее чтение клавиши. 0 = событие получено, 1 = пусто, -1 = нет ConIn. */
int lin_poll_key(u16 *out_scan, u16 *out_char);

/* Ожидание любой клавиши до timeout_ms. 0 = клавиша, 1 = таймаут, -1 = нет ConIn. */
int lin_wait_key(u32 timeout_ms, u16 *out_scan, u16 *out_char);

/* Опрос Shift через SimpleTextInputEx. 1 = Shift нажат (событие с shift-состоянием),
 * 0 = нет, -1 = EX-протокол недоступен. */
int lin_poll_shift(void);

/* Прямой опрос 8042 (порты 0x64/0x60): забирает ОДИН байт клавиатуры из
 * выходного буфера контроллера, если тот не пуст, и отдаёт его вызывающему.
 * Прошивочный PS/2-драйвер опрашивает контроллер по таймеру (~десятки мс);
 * наш опрос в окне boot manager — каждые ~5 мс, поэтому байт чаще достаётся
 * нам. Раньше функция называлась lin_poll_shift_direct и поглощала все
 * не-Shift байты — из-за этого нажатия ESC и I в окне пропадали (гонка за
 * выходной буфер с драйвером прошивки). Теперь байт интерпретирует окно
 * (oobe_esc_window): Shift, ESC, I — каждый съеденный байт обрабатывается.
 * Байты мыши (bit5 статуса) пропускаются.
 * Коды при translate=on (наш конфиг 8042, см. boot-лог): набор 1 —
 * ESC=0x01, I=0x17, LShift=0x2A, RShift=0x36. При translate=off коды
 * набора 2: ESC=0x76, I=0x43, LShift=0x12, RShift=0x59. Проверяются оба
 * набора (состояние трансляции до чтения конфига контроллера неизвестно).
 * 1 = клавиатурный байт получен (*out_code = make/break-код); 0 = буфер
 * пуст; -1 = out_code == NULL. */
int lin_poll_direct(u8 *out_code);

#endif /* FOBOS_UEFI_LIN_H */
