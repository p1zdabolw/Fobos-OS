/*
 * Fobos OS — менеджер виртуальной памяти (прототипы, FND-3a).
 *
 * Модель: один CR3 на процесс. Таблицы ядра (записи PML4 256..511 —
 * higher-half) и identity-отображение < 4 ГиБ (записи PML4 с PS-битом,
 * созданные загрузчиком) РАЗДЕЛЯЮТСЯ всеми процессами: новый PML4 получает
 * копии этих записей. User-память — 4 КиБ страницы в нижней половине
 * (PML4 0..255), флаги USER|RW, W^X: текст PT_LOAD с PF_X — без NX,
 * данные/стек/heap — NX.
 *
 * Ограничение FND-3a (задокументировано): физические кадры выдаются
 * ниже 4 ГиБ, где действует разделяемое identity-отображение, поэтому
 * ядро адресует страницы таблиц и user-кадры напрямую по физическому
 * адресу. Уход от identity-зависимости — собственное higher-half окно
 * ядра (FND-2 VMM, см. roadmap).
 */
#ifndef FOBOS_MM_VMM_H
#define FOBOS_MM_VMM_H

#include <fobos/errors.h>
#include <fobos/types.h>

/* Флаги маппинга user-страниц. */
#define VMM_PF_USER (1ull << 0)
#define VMM_PF_RW   (1ull << 1)
#define VMM_PF_NX   (1ull << 2)   /* EFER.NXE обязан быть включён (tss_init) */

/* Инициализация: фиксирует CR3 загрузчика как kernel-space прототип
 * (источник записей для новых пространств). Вызывается после phys_init. */
err_t vmm_init(void);

/* CR3 текущего kernel-пространства (прототип). */
u64 vmm_kernel_cr3(void);

/* Создаёт пустое адресное пространство: PML4-кадр + копии разделяемых
 * записей (identity + higher-half). */
err_t vmm_space_create(u64 *out_pml4);

/* Освобождает пространство: все user-страницы и таблицы нижней половины.
 * Записи с PS-битом (identity bigpages) и вся верхняя половина не
 * трогаются — они разделяемые. Пространство НЕ должно быть активным CR3. */
err_t vmm_space_destroy(u64 pml4);

/* Загружает CR3 (переключение адресного пространства). */
void vmm_space_load(u64 pml4);

/* Маппинг одной 4 КиБ страницы. Повторный вызов по тому же vaddr
 * перезаписывает PTE (используется для RX-переключения после записи
 * сегментов загрузчиком). Промежуточные таблицы аллоцируются по мере
 * надобности и учитываются для vmm_space_destroy. */
err_t vmm_map_page(u64 pml4, u64 vaddr, u64 paddr, u64 flags);

/* Снимает страницу и освобождает физический кадр (если present).
 * Промежуточные пустые таблицы НЕ освобождаются (учёт при destroy). */
err_t vmm_unmap_page(u64 pml4, u64 vaddr);

/* Проверка user-буфера: [uaddr, uaddr+len) полностью замаплена как
 * USER-страницы (P|U). Используется syscall-слоем перед копированием.
 * len == 0 — валидно (K_OK без проверки). */
err_t vmm_user_range_ok(u64 pml4, u64 uaddr, u64 len);

/* Статистика (диагностика/ps/mem). */
struct vmm_stats {
    u64 user_frames;      /* мапнуто user-кадров во всех пространствах */
    u64 page_tables;      /* аллоцировано таблиц (PDPT/PD/PT) под user */
    u64 spaces;           /* живых пространств */
};
struct vmm_stats vmm_get_stats(void);

#endif /* FOBOS_MM_VMM_H */
