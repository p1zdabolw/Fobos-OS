/*
 * Fobos OS — экран загрузки (splash) и детектор «Shift -> консоль ядра».
 *
 * Логика (аналог GRUB "press ESC for menu" / Windows "Shift + Перезагрузка"):
 *  - после самопроверок ядро рисует splash с подсказкой и держит окно
 *    FOBOS_SPLASH_MS (3 с), в котором слушает клавиатуру;
 *  - если в окне зафиксирован удерживаемый Shift (событие/состояние
 *    модификаторов) — загрузка идёт в режим kernel console (kshell),
 *    минуя экран входа (режим диагностики/обслуживания);
 *  - иначе — обычный поток: экран входа / OOBE-подсказка.
 *
 * Почему окно после init клавиатуры, а не в загрузчике: состояние Shift
 * не переживает reset (8042 сбрасывается), а прошивка OVMF может
 * «съесть» сканкоды до передачи управления. Открытое окно с подсказкой
 * детерминировано и работает на реальном железе (тип-матика/повторное
 * нажатие в окне всегда даёт make-код Shift).
 */
#ifndef FOBOS_GFX_SPLASH_H
#define FOBOS_GFX_SPLASH_H

#include <fobos/types.h>

#define FOBOS_SPLASH_MS 3000u

/* Рисует splash и ждёт окно window_ms.
 * Возвращает 1, если зафиксирован Shift (-> консоль), 0 — иначе. */
int splash_wait(u32 window_ms);

#endif /* FOBOS_GFX_SPLASH_H */
