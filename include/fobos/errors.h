/*
 * Fobos OS — единая конвенция кодов ошибок.
 *
 * Правило проекта: каждый публичный API подсистемы возвращает err_t.
 * 0 — успех, отрицательные значения — ошибка. Вызывающий код ОБЯЗАН
 * обработать код (залогировать/пробросить/восстановиться); молчаливое
 * игнорирование запрещено стилем проекта.
 */
#ifndef FOBOS_ERRORS_H
#define FOBOS_ERRORS_H

#include <fobos/types.h>

typedef int err_t;

#define K_OK            0   /* успех */
#define K_EINVAL       -1   /* недопустимый аргумент / повреждённые данные */
#define K_ENOMEM       -2   /* недостаточно ресурсов (память, кадры) */
#define K_ENODEV       -3   /* устройство отсутствует */
#define K_EIO          -4   /* ошибка ввода-вывода */
#define K_EUNSUPPORTED -5   /* операция не поддерживается оборудованием/этапом */
#define K_ESTATE       -6   /* подсистема не инициализирована или в неверном состоянии */
#define K_ERANGE       -7   /* выход за допустимые границы значения */
#define K_EAGAIN       -8   /* данных пока нет — повторите попытку (poll-API) */
#define K_ENOENT       -9   /* не найдено (конец каталога, отсутствие записи) */
#define K_EEXIST       -10  /* уже существует (коллизия имени, повторный ресурс) */
#define K_EPERM        -11  /* операция не разрешена (права/контекст вызова) */
#define K_ENOSYS       -12  /* функция ABI не реализована (для syscall/ELF) */

const char *k_strerror(err_t code);

#endif /* FOBOS_ERRORS_H */
