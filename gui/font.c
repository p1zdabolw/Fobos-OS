void font_init(void) { }

static void draw_glyph(int x, int y, const u8 *glyph, u32 fg, u32 bg) {
    for (int row = 0; row < 8; row++) {
        u8 bits = glyph[row];
        for (int dy = 0; dy < 2; dy++) {
            for (int col = 0; col < 8; col++) {
                u32 c = (bits & (0x80 >> col)) ? fg : bg;
                fb_put_pixel(x + col, y + row * 2 + dy, c);
            }
        }
    }
}

void font_draw_char(int x, int y, char c, u32 fg, u32 bg) {
    u8 idx = (u8)c;
    if (idx < 32) return;
    if (idx <= 126) {
        draw_glyph(x, y, (const u8*)g_font[idx - 32], fg, bg);
        return;
    }
    if (idx >= 0xC0) {
        draw_glyph(x, y, (const u8*)g_font_cyr[idx - 0xC0], fg, bg);
        return;
    }
    draw_glyph(x, y, (const u8*)g_font['?' - 32], fg, bg);
}

void font_draw_string(int x, int y, const char *s, u32 fg, u32 bg) {
    int cx = x;
    while (*s) {
        font_draw_char(cx, y, *s, fg, bg);
        cx += FONT_W;
        s++;
    }
}

void font_draw_string_alpha(int x, int y, const char *s, u32 fg, u32 bg) {
    font_draw_string(x, y, s, fg, bg);
}

int font_text_width(const char *s) {
    int n = 0;
    while (s[n]) n++;
    return n * FONT_W;
}